def charts(result: dict, out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    plt.rcParams.update({"font.family":"DejaVu Sans","font.size":10,"svg.fonttype":"none"})
    names = ["Static\nlogistic","Temporal\nboosting","INVALID\nfuture marker"]
    keys = ["static_logistic","temporal_boosting","INVALID_future_marker"]
    colors = ["#516b86","#127d80","#b9574b"]
    fig,axes = plt.subplots(1,2,figsize=(10.8,4.6))
    for ax,metric,title in zip(axes,["average_precision","precision_at_daily_budget"],
                              ["Ranking quality on the frozen holdout","Yield at identical daily review capacity"]):
        values = [np.nan if result["test"][key][metric] is None else result["test"][key][metric] for key in keys]
        ax.bar(names,values,color=colors,width=.6)
        ax.set_ylim(0,1)
        ax.set_title(title,loc="left",fontweight="bold",fontsize=11)
        ax.set_ylabel("Average precision" if metric=="average_precision" else "Precision among reviewed transactions")
        for i,value in enumerate(values):
            ax.text(i,.025 if np.isnan(value) else value+.025,
                    "N/A" if np.isnan(value) else f"{value:.3f}",ha="center",fontsize=10)
        ax.spines[["right","top"]].set_visible(False)
        ax.grid(axis="y",alpha=.15)
        ax.set_axisbelow(True)
    fig.suptitle("A future outcome marker can look strong and still be unusable",x=.05,ha="left",fontweight="bold",fontsize=14)
    fig.text(.05,.015,"Synthetic data. The red diagnostic violates availability; it is never eligible for deployment.",fontsize=9)
    fig.tight_layout(rect=(.025,.06,.99,.91))
    fig.savefig(out/"model-comparison.svg",metadata={"Creator":None,"Date":None})
    plt.close(fig)
    fig,ax = plt.subplots(figsize=(8.5,4.7))
    x = np.arange(2)
    for offset,key,label,color in [(-.18,"static_logistic","Static logistic",colors[0]),
                                  (.18,"temporal_boosting","Temporal boosting",colors[1])]:
        values = [np.nan if result["test_segments"][name][key]["average_precision"] is None
                  else result["test_segments"][name][key]["average_precision"] for name in ("original","shifted")]
        bars = ax.bar(x+offset,values,width=.34,label=label,color=color)
        for position,value in zip(x+offset,values):
            ax.text(position,.025 if np.isnan(value) else value+.015,
                    "N/A" if np.isnan(value) else f"{value:.3f}",ha="center",fontsize=10)
    ax.set_xticks(x,["Days 67-71\noriginal mechanism","Days 72-89\ndeclared shifted mechanism"])
    ax.set_ylim(0,1)
    ax.set_ylabel("Average precision")
    ax.set_title("Audit the frozen model when the signal changes",loc="left",fontweight="bold",pad=15)
    ax.spines[["right","top"]].set_visible(False)
    ax.grid(axis="y",alpha=.15)
    ax.set_axisbelow(True)
    ax.legend(frameon=False,loc="upper right")
    fig.text(.075,.015,"Synthetic, unequal windows. N/A: no positive labels; compare counts and prevalence in the report.",fontsize=9)
    fig.tight_layout(rect=(.025,.06,.99,1))
    fig.savefig(out/"shift-comparison.svg",metadata={"Creator":None,"Date":None})
    plt.close(fig)
